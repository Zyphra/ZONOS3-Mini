#!/usr/bin/env python3
"""Emit src/unicode-data.h: the Unicode tables of the native text code.

    uv run --python 3.12 scripts/gen-unicode-data.py > src/unicode-data.h

- \\p{L} and \\p{N} code-point ranges, used by the SuperBPE pre-tokenizer.
- General_Category M ranges, str.isspace() ranges, the character classes of
  zonos3/tts/phonemes.py ``_char_class``, and the NFC and str.casefold() data
  (canonical combining classes, canonical decompositions, primary composites,
  full case folding), used by the pronunciation lexicon (src/zonos3-phonemes.cpp).
- Python str.upper() and str.lower() (full case mappings), used by the text
  matching of speech editing (src/zonos3-textmatch.cpp: zonos3/tts/textmatch.py).

Python 3.12's unicodedata is Unicode 15.0, the version of the Oniguruma bundled with tokenizers 0.22
and of the Python that runs the reference.
"""
import sys
import unicodedata

CATS = {
    "L": {"Lu", "Ll", "Lt", "Lm", "Lo"},
    "N": {"Nd", "Nl", "No"},
}
# phonemes.py _char_class (letters only); 0 = not one of these classes.
HIRA, KATA, HANGUL, HAN = 1, 2, 3, 4


def runs(value):
    """Maximal runs of equal non-zero value(cp): [(start, end, value)]."""
    out = []
    start = cur = None
    for cp in range(0x110000):
        v = value(cp)
        if v != cur:
            if cur:
                out.append((start, cp - 1, cur))
            start, cur = cp, v
    if cur:
        out.append((start, 0x10FFFF, cur))
    return out


def ranges(cats):
    return [(a, b) for a, b, _ in runs(lambda cp: unicodedata.category(chr(cp)) in cats)]


def char_class(cp):
    c = chr(cp)
    if not unicodedata.category(c).startswith("L"):
        return 0
    name = unicodedata.name(c, "")
    if name.startswith("HIRAGANA"):
        return HIRA
    if name.startswith("KATAKANA"):
        return KATA
    if name.startswith("HANGUL SYLLABLE"):
        return HANGUL
    if "CJK UNIFIED IDEOGRAPH" in name or "CJK COMPATIBILITY IDEOGRAPH" in name or c == "々":
        return HAN
    return 0


def canonical_decomposition(cp):
    d = unicodedata.decomposition(chr(cp))
    if not d or d.startswith("<"):
        return None
    parts = [int(x, 16) for x in d.split()]
    assert 1 <= len(parts) <= 2, hex(cp)
    return parts


def emit(w, comment, decl, rows, per_line=4):
    w(f"\n// {comment}\n{decl} = {{\n")
    for i in range(0, len(rows), per_line):
        w("    " + " ".join("{" + ", ".join(f"0x{v:X}" for v in row) + "}," for row in rows[i:i + per_line]) + "\n")
    w("};\n")


def main():
    w = sys.stdout.write
    w("// Generated by scripts/gen-unicode-data.py; do not edit.\n")
    w(f"// Unicode {unicodedata.unidata_version}: inclusive code-point ranges, sorted.\n")
    w("#pragma once\n\n#include <cstdint>\n")
    for name, cats in CATS.items():
        emit(w, f"General_Category in {{{', '.join(sorted(cats))}}}",
             f"static const uint32_t ZONOS3_UNI_{name}[][2]", ranges(cats))

    emit(w, "General_Category in {Mc, Me, Mn}", "static const uint32_t ZONOS3_UNI_M[][2]",
         ranges({"Mn", "Mc", "Me"}))
    emit(w, "Python str.isspace()", "static const uint32_t ZONOS3_UNI_SPACE[][2]",
         [(a, b) for a, b, _ in runs(lambda cp: chr(cp).isspace())])
    w(f"\nenum {{ ZONOS3_UNI_HIRA = {HIRA}, ZONOS3_UNI_KATA = {KATA}, ZONOS3_UNI_HANGUL = {HANGUL}, "
      f"ZONOS3_UNI_HAN = {HAN} }};\n")
    emit(w, "{first, last, class}: letters whose name marks them HIRAGANA / KATAKANA / HANGUL SYLLABLE / CJK ideograph",
         "static const uint32_t ZONOS3_UNI_CJK_CLASS[][3]", runs(char_class), per_line=3)
    emit(w, "{first, last, canonical combining class} for every non-zero class",
         "static const uint32_t ZONOS3_UNI_CCC[][3]", runs(lambda cp: unicodedata.combining(chr(cp))), per_line=3)

    decomp, compose = [], []
    for cp in range(0x110000):
        parts = canonical_decomposition(cp)
        if parts is None:
            continue
        decomp.append((cp, parts[0], parts[1] if len(parts) == 2 else 0))
        if len(parts) == 2 and unicodedata.normalize("NFC", chr(cp)) == chr(cp):
            compose.append((parts[0], parts[1], cp))
    assert unicodedata.decomposition("\uAC00") == ""  # Hangul syllables are algorithmic
    compose.sort()
    emit(w, "{code point, first, second (0 = singleton)}: canonical decomposition mappings (one level; Hangul is algorithmic)",
         "static const uint32_t ZONOS3_UNI_DECOMP[][3]", decomp, per_line=3)
    emit(w, "{first, second, composite} sorted by (first, second): primary composites (composition exclusions removed)",
         "static const uint32_t ZONOS3_UNI_COMPOSE[][3]", compose, per_line=3)

    fold = []
    for cp in range(0x110000):
        c = chr(cp)
        f = c.casefold()
        if f != c:
            assert len(f) <= 3, hex(cp)
            fold.append((cp, len(f), *(ord(x) for x in f), *([0] * (3 - len(f)))))
    emit(w, "{code point, length, folded[3]}: Python str.casefold() (full case folding)",
         "static const uint32_t ZONOS3_UNI_CASEFOLD[][5]", fold, per_line=2)

    for name, method in (("UPPER", str.upper), ("LOWER", str.lower)):
        rows = []
        for cp in range(0x110000):
            c = chr(cp)
            m = method(c)
            if m != c:
                assert len(m) <= 3, hex(cp)
                rows.append((cp, len(m), *(ord(x) for x in m), *([0] * (3 - len(m)))))
        emit(w, f"{{code point, length, mapped[3]}}: Python str.{name.lower()}() of one character (full case mapping)",
             f"static const uint32_t ZONOS3_UNI_{name}[][5]", rows, per_line=2)

    # str.lower()'s Final_Sigma context (CPython handle_capital_sigma): case-ignorable characters are skipped, then the
    # neighbour must (before) / must not (after) be cased. Probed through str.lower() itself: the cased-ness of a
    # case-ignorable character is never read.
    def sigma_class(cp):
        c = chr(cp)
        if (c + "\u03a3").lower()[-1] == "\u03c2":
            return 2   # cased, not case-ignorable
        return 1 if ("A" + c + "\u03a3").lower()[-1] == "\u03c2" else 0
    emit(w, "{first, last, class}: str.lower() Final_Sigma context classes (1 case-ignorable, 2 cased)",
         "static const uint32_t ZONOS3_UNI_SIGMA_CONTEXT[][3]", runs(sigma_class), per_line=3)


if __name__ == "__main__":
    main()
